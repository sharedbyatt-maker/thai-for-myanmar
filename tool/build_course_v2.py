"""Authored course data. No phrase-category chunking or automatic translation."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
lines = {}
units = []
manifest = json.loads((ROOT / 'assets/data/thai_audio_manifest.json').read_text())['entries']


def word(thai, my):
    key = 'c2_w_' + hashlib.sha256((thai + '\n' + my).encode()).hexdigest()[:12]
    if key not in lines:
        sources = {style: next((e['phraseId'] for e in manifest if e['thai'] == thai and e['form'] in [style, 'shared']), '') for style in ['male', 'female']}
        lines[key] = dict(id=key, male=thai, female=thai, my=my, parts={}, sources=sources, question=False)
    return key


def pairs(text):
    return [tuple(item.split('=', 1)) for item in text.split(';')]


def m(parts, my, scene, q=False):
    return dict(parts=pairs(parts), my=my, scene=scene, question=q)


def unit(n, section, title, goal, vocabulary, tips, models, deps, dialogue=None):
    uid = f'u{n:02}'
    words = [word(t, y) for t, y in pairs(vocabulary)]
    mids = []
    for i, model in enumerate(models):
        lid = f'c2_{uid}_{i+1:02}'
        bodies, part_ids = {}, {}
        for style in ['male', 'female']:
            ps = []
            for thai, my in model['parts']:
                if style == 'female':
                    if thai == 'ผม':
                        thai, my = 'ฉัน', 'ကျွန်မ'
                    if n == 1 and thai in ['เอก', 'ต้น']:
                        thai, my = {'เอก': ('มาลี', 'မလီ'), 'ต้น': ('นิดา', 'နီဒါ')}[thai]
                ps.append((thai, my))
            ending = 'ครับ' if style == 'male' else ('คะ' if model['question'] else 'ค่ะ')
            bodies[style] = ''.join(t for t, _ in ps) + ending
            part_ids[style] = [word(t, y) for t, y in ps] + [word(ending, 'ယဉ်ကျေးအဆုံးသတ်')]
        sources = {style: next((e['phraseId'] for e in manifest if e['thai'] == bodies[style] and e['form'] in [style, 'shared']), '') for style in bodies}
        lines[lid] = dict(id=lid, **bodies, my=model['my'], scene=model['scene'], parts=part_ids, sources=sources, question=model['question'])
        if n == 1 and i in [2, 4]:
            lines[lid]['myMale'] = 'နာမည်က ' + ('အေ့က်' if i == 2 else 'တုန့်') + ' ပါ။'
            lines[lid]['myFemale'] = 'နာမည်က ' + ('မလီ' if i == 2 else 'နီဒါ') + ' ပါ။'
        mids.append(lid)
    lessons = []

    def lesson(title, steps):
        lessons.append(dict(id=f'{uid}-l{len(lessons)+1:02}', title=title, steps=steps))

    def steps(kind, ids):
        return [dict(kind=kind, line=x) for x in ids]

    if n == 1:
        lesson('နှုတ်ဆက်၊ ကျေးဇူးတင်', steps('teach', mids[:2]) + steps('choice', mids[:2]))
        lesson('ကိုယ့်နာမည် ပြောမယ်', steps('teach', [mids[2]]) + steps('build', [mids[2]]))
        lesson('နာမည် ပြန်မေးမယ်', steps('teach', [mids[3]]) + steps('choice', [mids[3]]) + steps('build', [mids[3]]))
        lesson('နာမည်ပြောင်း သုံးမယ်', steps('notice', [mids[4]]) + steps('build', [mids[4]]))
    else:
        for start in range(0, len(words), 5):
            lesson('စကားလုံးအခြေခံ' + (f' · {start//5+1}' if len(words) > 5 else ''), steps('teach', words[start:start+5]))
        lesson('ဝါကျပုံစံကို သုံးမယ်', steps('teach', mids[:2]) + steps('build', mids[:2]))
        lesson('မေးပြီး ပြန်ဖြေမယ်', steps('teach', mids[2:-1]) + steps('choice', mids[2:-1]))
        lesson('အစားထိုး သုံးမယ်', steps('notice', [mids[-1]]) + steps('build', [mids[-1]]))
    lesson('စကားဝိုင်း လေ့ကျင့်မယ်', [dict(kind='dialogue', lines=[mids[i] for i in (dialogue if dialogue is not None else range(min(4, len(mids))))])])
    lesson('ကိုယ်တိုင် ပြန်စမ်းမယ်', steps('choice', mids) + steps('build', [mids[-1]]) + [dict(kind='reflect')])
    units.append(dict(id=uid, section=section, title=title, goal=goal, prerequisites=[f'u{x:02}' for x in deps], words=words, models=mids, tips=tips, lessons=lessons))


