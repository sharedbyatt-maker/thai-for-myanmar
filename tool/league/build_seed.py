"""Build reviewed question catalog from existing lesson order; no new content."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
phrases = json.loads((root / 'assets/data/phrases.json').read_text())
categories = json.loads((root / 'assets/data/phrase_categories.json').read_text())
def quote(text):
    return "'" + text.replace("'", "''") + "'"
rows = []
for category in categories:
    group = [p for p in phrases if p['categoryId'] == category['id']]
    for offset in range(0, len(group), 5):
        lesson = f"{category['id']}:{group[offset]['id']}"
        for phrase in group[offset:offset+5]:
            rows.append('(' + ','.join(map(quote, [phrase['id'], lesson, phrase.get('thaiFemale') or phrase['thai'], phrase['my']])) + ')')
(root / 'supabase/migrations/20261030112659_question_catalog.sql').write_text(
    '-- Generated by tool/league/build_seed.py from bundled content.\n'
    'insert into league_private.questions(id, lesson_id, thai, meaning) values\n'
    + ',\n'.join(rows) + '\non conflict(id) do update set lesson_id=excluded.lesson_id, thai=excluded.thai, meaning=excluded.meaning;\n')
print(f'{len(rows)} questions seeded')
